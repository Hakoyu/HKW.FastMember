using System.CodeDom.Compiler;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using HKW.FastMember.Generater.SourceGenerator.Models;
using HKW.SourceGeneratorUtils;
using Microsoft.CodeAnalysis;

namespace HKW.FastMember.Generater.SourceGenerator.Emission;

internal static class AccessorEmitter
{
    private static string Literal(string value) =>
        Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private static string Bool(bool value) => value ? "true" : "false";

    internal static string Emit(
        string type,
        string identifier,
        IReadOnlyList<MemberModel> members,
        bool constructible
    )
    {
        using var text = new StringWriter(CultureInfo.InvariantCulture) { NewLine = "\n" };
        using var writer = new IndentedTextWriter(text, "    ");
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("namespace HKW.FastMember.Generater");
        writer.WriteLine("{");
        writer.Indent++;
        writer.WriteLine(GeneratorHelper.GeneratedCodeAttributeName);
        writer.WriteLine(
            $"internal sealed class Accessor_{identifier} : global::HKW.FastMember.Abstractions.TypeAccessor<{type}>"
        );
        writer.WriteLine("{");
        writer.Indent++;
        WriteDescriptors(writer, members);
        new ConstructorGenerateInfo("Accessor_" + identifier)
        {
            Accessibility = Accessibility.Internal,
            Initializer = $"base(Descriptors, {Bool(constructible)}, 1)",
        }.WriteTo(writer);
        writer.WriteLine();
        writer.WriteInfo(CreateReadMethod(type, members));
        writer.WriteLine();
        writer.WriteInfo(CreateWriteMethod(type, members));
        if (constructible)
        {
            writer.WriteLine();
            writer.WriteInfo(
                new MethodGenerateInfo(type, "CreateNewTypedCore", $"return new {type}();")
                {
                    Accessibility = Accessibility.Protected,
                    GenerateType = MethodGenerateType.Override,
                    AddDefaultAttributes = false,
                }
            );
        }
        writer.Indent--;
        writer.WriteLine("}");
        writer.WriteLine();
        RegistrationEmitter.WriteTo(writer, type, identifier);
        writer.Indent--;
        writer.WriteLine("}");
        return text.ToString();
    }

    private static void WriteDescriptors(
        IndentedTextWriter writer,
        IReadOnlyList<MemberModel> members
    )
    {
        writer.WriteLine(
            "private static readonly global::HKW.FastMember.Abstractions.Member[] Descriptors = new global::HKW.FastMember.Abstractions.Member[]"
        );
        writer.WriteLine("{");
        writer.Indent++;
        foreach (var member in members)
        {
            writer.WriteLine(
                $"new global::HKW.FastMember.Abstractions.Member({Literal(member.Name)}, typeof({member.Type}), "
                    + $"{member.Ordinal.ToString(CultureInfo.InvariantCulture)}, {Bool(member.CanRead)}, {Bool(member.CanWrite)}, "
                    + $"{Literal(member.Identity)}, typeof({member.EffectiveType}), {Bool(member.AllowNull)}),"
            );
        }
        writer.Indent--;
        writer.WriteLine("};");
    }

    private static MethodGenerateInfo CreateReadMethod(
        string type,
        IReadOnlyList<MemberModel> members
    )
    {
        var method = CreateAccessMethod("object?", "GetValueTypedCore", type);
        method.Contents.Add("switch (index)");
        method.Contents.Add("{");
        for (var i = 0; i < members.Count; i++)
        {
            if (!members[i].CanRead)
                continue;
            method.Contents.Add($"    case {i.ToString(CultureInfo.InvariantCulture)}:");
            method.Contents.Add(
                $"        return (({members[i].DeclaringType})target).@{members[i].Name};"
            );
        }
        AddDefaultCase(method);
        return method;
    }

    private static MethodGenerateInfo CreateWriteMethod(
        string type,
        IReadOnlyList<MemberModel> members
    )
    {
        var method = CreateAccessMethod("void", "SetValueTypedCore", type);
        method.Params!.Add(new ParameterGenerateInfo("object?", "value"));
        method.Contents.Add("switch (index)");
        method.Contents.Add("{");
        for (var i = 0; i < members.Count; i++)
        {
            if (!members[i].CanWrite)
                continue;
            method.Contents.Add($"    case {i.ToString(CultureInfo.InvariantCulture)}:");
            method.Contents.Add(
                $"        (({members[i].DeclaringType})target).@{members[i].Name} = ({members[i].Type})value!;"
            );
            method.Contents.Add("        return;");
        }
        AddDefaultCase(method);
        return method;
    }

    private static MethodGenerateInfo CreateAccessMethod(
        string returnType,
        string name,
        string type
    ) =>
        new(returnType, name, "")
        {
            Accessibility = Accessibility.Protected,
            GenerateType = MethodGenerateType.Override,
            AddDefaultAttributes = false,
            Params = new List<ParameterGenerateInfo> { new(type, "target"), new("int", "index") },
        };

    private static void AddDefaultCase(MethodGenerateInfo method)
    {
        method.Contents.Add("    default:");
        method.Contents.Add(
            "        throw new global::System.ArgumentOutOfRangeException(nameof(index));"
        );
        method.Contents.Add("}");
    }
}

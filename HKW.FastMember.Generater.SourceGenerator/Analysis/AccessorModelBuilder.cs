using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using HKW.FastMember.Generater.SourceGenerator.Emission;
using HKW.FastMember.Generater.SourceGenerator.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace HKW.FastMember.Generater.SourceGenerator.Analysis;

internal static class AccessorModelBuilder
{
    internal static bool IsEntry(IMethodSymbol? method) =>
        method != null
        && method.Name == "Create"
        && method.IsStatic
        && method.Arity == 1
        && method.ContainingType.Arity == 0
        && method.ContainingAssembly.Identity.Name == "HKW.FastMember.Generater"
        && method.ContainingNamespace.ToDisplayString() == "HKW.FastMember.Generater"
        && (
            method.ContainingType.Name == "TypeAccessor"
            || method.ContainingType.Name == "ObjectAccessor"
            || method.ContainingType.Name == "ObjectReader"
        );

    internal static bool IsGenerated(
        SyntaxNode node,
        SemanticModel semantic,
        CancellationToken token
    )
    {
        var path = node.SyntaxTree.FilePath;
        if (
            path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
        )
            return true;
        var text = node.SyntaxTree.GetText(token);
        if (
            text.ToString(new Microsoft.CodeAnalysis.Text.TextSpan(0, Math.Min(256, text.Length)))
                .Contains("<auto-generated")
        )
            return true;
        for (
            var symbol = semantic.GetEnclosingSymbol(node.SpanStart, token);
            symbol != null;
            symbol = symbol.ContainingSymbol
        )
            if (
                symbol
                    .GetAttributes()
                    .Any(a =>
                        a.AttributeClass?.ToDisplayString()
                        == "System.CodeDom.Compiler.GeneratedCodeAttribute"
                    )
            )
                return true;
        return false;
    }

    internal static IMethodSymbol? FindEntry(
        InvocationExpressionSyntax node,
        SemanticModel semantic,
        CancellationToken token
    )
    {
        var info = semantic.GetSymbolInfo(node, token);
        if (info.Symbol is IMethodSymbol method && IsEntry(method))
            return method;
        if (info.CandidateReason == CandidateReason.LateBound)
            return null;
        return info.CandidateSymbols.OfType<IMethodSymbol>().FirstOrDefault(IsEntry);
    }

    internal static bool IsDynamicEntry(
        InvocationExpressionSyntax node,
        SemanticModel semantic,
        CancellationToken token
    )
    {
        var info = semantic.GetSymbolInfo(node, token);
        return node.ArgumentList.Arguments.Any(a =>
                semantic.GetTypeInfo(a.Expression, token).Type?.TypeKind == TypeKind.Dynamic
            )
            && (
                IsEntry(info.Symbol as IMethodSymbol)
                || info.CandidateSymbols.OfType<IMethodSymbol>().Any(IsEntry)
                || semantic
                    .GetMemberGroup(node.Expression, token)
                    .OfType<IMethodSymbol>()
                    .Any(IsEntry)
            );
    }

    internal static AnalysisResult? Analyze(GeneratorSyntaxContext context, CancellationToken token)
    {
        var node = (InvocationExpressionSyntax)context.Node;
        if (
            IsGenerated(node, context.SemanticModel, token)
            || IsDynamicEntry(node, context.SemanticModel, token)
        )
            return null;
        var method = FindEntry(node, context.SemanticModel, token);
        if (method == null)
            return null;
        var type = method.TypeArguments[0];
        var compilation = context.SemanticModel.Compilation;
        var errors = ImmutableArray.CreateBuilder<Diagnostic>();
        var location = node.GetLocation();
        if (
            !(type is INamedTypeSymbol named)
            || named.TypeKind != TypeKind.Class
            || named.SpecialType == SpecialType.System_Object
            || named.IsAnonymousType
            || named.IsStatic
            || ContainsTypeParameter(type)
            || IsDynamicModel(named)
        )
        {
            errors.Add(
                Diagnostic.Create(
                    Diagnostics.UnsupportedType,
                    location,
                    type.ToDisplayString(),
                    "a concrete non-dynamic class is required"
                )
            );
            return new AnalysisResult(null, errors.ToImmutable());
        }
        if (!IsNameable(named, compilation))
        {
            errors.Add(
                Diagnostic.Create(Diagnostics.InaccessibleType, location, type.ToDisplayString())
            );
            return new AnalysisResult(null, errors.ToImmutable());
        }
        if (!BindsUniquely(named, compilation))
        {
            errors.Add(
                Diagnostic.Create(Diagnostics.AmbiguousType, location, type.ToDisplayString())
            );
            return new AnalysisResult(null, errors.ToImmutable());
        }
        var members = new Dictionary<string, MemberModel>(StringComparer.Ordinal);
        for (var current = named; current != null; current = current.BaseType)
        {
            token.ThrowIfCancellationRequested();
            var eligible = current
                .GetMembers()
                .Where(IsEligible)
                .GroupBy(s => s.Name, StringComparer.Ordinal);
            foreach (var group in eligible)
            {
                if (members.ContainsKey(group.Key))
                    continue;
                if (group.Count() != 1)
                {
                    errors.Add(Diagnostic.Create(Diagnostics.AmbiguousMember, location, group.Key));
                    continue;
                }
                var member = group.First();
                var property = member as IPropertySymbol;
                var field = member as IFieldSymbol;
                var memberType = property?.Type ?? field!.Type;
                if (
                    property?.ReturnsByRef == true
                    || property?.ReturnsByRefReadonly == true
                    || Unboxable(memberType)
                )
                {
                    errors.Add(
                        Diagnostic.Create(
                            Diagnostics.UnsupportedMember,
                            location,
                            member.ToDisplayString(),
                            "ref returns, ref-like and pointer types are not supported"
                        )
                    );
                    continue;
                }
                var read =
                    field != null
                    || property!.GetMethod?.DeclaredAccessibility == Accessibility.Public;
                var write =
                    field != null
                        ? !field.IsReadOnly
                        : property!.SetMethod?.DeclaredAccessibility == Accessibility.Public
                            && !property.SetMethod.IsInitOnly;
                if (
                    !IsNameable(memberType, compilation)
                    || !IsNameable(current, compilation)
                    || !BindsUniquely(memberType, compilation)
                    || !BindsUniquely(current, compilation)
                    || (
                        !SyntaxFacts.IsValidIdentifier(member.Name)
                        && SyntaxFacts.GetKeywordKind(member.Name) == SyntaxKind.None
                    )
                    || IsObsoleteError(member)
                    || (read && property?.GetMethod != null && IsObsoleteError(property.GetMethod))
                    || (write && property?.SetMethod != null && IsObsoleteError(property.SetMethod))
                )
                {
                    errors.Add(
                        Diagnostic.Create(
                            Diagnostics.IllegalAccess,
                            location,
                            member.ToDisplayString(),
                            "its type, name or accessor is inaccessible, ambiguous or obsolete with an error"
                        )
                    );
                    continue;
                }
                var ordinal = -1;
                var attribute = member
                    .GetAttributes()
                    .FirstOrDefault(a =>
                        a.AttributeClass?.ToDisplayString()
                            == "HKW.FastMember.Abstractions.OrdinalAttribute"
                        && a.AttributeClass.ContainingAssembly.Identity.Name
                            == "HKW.FastMember.Abstractions"
                    );
                if (
                    attribute != null
                    && attribute.ConstructorArguments.Length == 1
                    && attribute.ConstructorArguments[0].Value is int value
                )
                    ordinal = value;
                var nullable =
                    memberType is INamedTypeSymbol mt
                    && mt.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
                var effective = nullable
                    ? ((INamedTypeSymbol)memberType).TypeArguments[0]
                    : memberType;
                var declaringType = TypeName(current);
                var identity =
                    current.ContainingAssembly.Identity
                    + "|"
                    + declaringType
                    + "|"
                    + member.Kind
                    + "|"
                    + member.Name;
                members.Add(
                    member.Name,
                    new MemberModel(
                        member.Name,
                        TypeName(memberType),
                        declaringType,
                        identity,
                        ordinal,
                        read,
                        write,
                        TypeName(effective),
                        memberType.IsReferenceType || nullable
                    )
                );
            }
        }
        if (errors.Count != 0)
            return new AnalysisResult(null, errors.ToImmutable());
        var ordered = members.Values.OrderBy(m => m.Name, StringComparer.Ordinal).ToArray();
        var identityKey = named.ContainingAssembly.Identity + "|" + TypeName(named);
        string identifier;
        using (var sha = SHA256.Create())
            identifier = BitConverter
                .ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(identityKey)))
                .Replace("-", "");
        var source = AccessorEmitter.Emit(
            TypeName(named),
            identifier,
            ordered,
            CanConstruct(named)
        );
        return new AnalysisResult(
            new AccessorModel(identityKey, TypeName(named), identifier, source),
            errors.ToImmutable()
        );
    }

    private static bool IsEligible(ISymbol symbol) =>
        symbol.DeclaredAccessibility == Accessibility.Public
        && !symbol.IsStatic
        && (
            (symbol is IPropertySymbol property && !property.IsIndexer)
            || (symbol is IFieldSymbol field && !field.IsConst && !field.IsImplicitlyDeclared)
        );

    private static bool Unboxable(ITypeSymbol type) =>
        type.IsRefLikeType
        || type.TypeKind == TypeKind.Pointer
        || type.TypeKind == TypeKind.FunctionPointer;

    private static bool ContainsTypeParameter(ITypeSymbol type) =>
        type.TypeKind == TypeKind.TypeParameter
        || (type is IArrayTypeSymbol array && ContainsTypeParameter(array.ElementType))
        || (
            type is INamedTypeSymbol named
            && (
                named.IsUnboundGenericType
                || named.TypeArguments.Any(ContainsTypeParameter)
                || (named.ContainingType != null && ContainsTypeParameter(named.ContainingType))
            )
        );

    private static bool IsDynamicModel(INamedTypeSymbol type) =>
        type.AllInterfaces.Any(i =>
            i.ToDisplayString() == "System.Dynamic.IDynamicMetaObjectProvider"
        );

    private static bool IsNameable(ITypeSymbol type, Compilation compilation)
    {
        if (type.TypeKind == TypeKind.Dynamic)
            return true;
        if (type is IArrayTypeSymbol array)
            return IsNameable(array.ElementType, compilation);
        if (
            !(type is INamedTypeSymbol named)
            || named.IsAnonymousType
            || named.IsFileLocal
            || ContainsTypeParameter(named)
        )
            return false;
        return compilation.IsSymbolAccessibleWithin(named, compilation.Assembly)
            && named.TypeArguments.All(t => IsNameable(t, compilation))
            && (named.ContainingType == null || IsNameable(named.ContainingType, compilation));
    }

    private static bool BindsUniquely(ITypeSymbol type, Compilation compilation)
    {
        if (type.TypeKind == TypeKind.Dynamic)
            return true;
        if (type is IArrayTypeSymbol array)
            return BindsUniquely(array.ElementType, compilation);
        if (!(type is INamedTypeSymbol named))
            return false;
        if (named.IsTupleType)
            named = named.TupleUnderlyingType!;
        var original = named.OriginalDefinition;
        var reference = compilation.GetMetadataReference(original.ContainingAssembly);
        if (
            reference != null
            && reference.Properties.Aliases.Length != 0
            && !reference.Properties.Aliases.Contains("global")
        )
            return false;
        var metadata = original.MetadataName;
        for (
            var containing = original.ContainingType;
            containing != null;
            containing = containing.ContainingType
        )
            metadata = containing.MetadataName + "+" + metadata;
        if (!original.ContainingNamespace.IsGlobalNamespace)
            metadata = original.ContainingNamespace.ToDisplayString() + "." + metadata;
        return SymbolEqualityComparer.Default.Equals(
                compilation.GetTypeByMetadataName(metadata),
                original
            )
            && named.TypeArguments.All(t => BindsUniquely(t, compilation))
            && (named.ContainingType == null || BindsUniquely(named.ContainingType, compilation));
    }

    private static bool IsObsoleteError(ISymbol symbol) =>
        symbol
            .GetAttributes()
            .Any(a =>
                a.AttributeClass?.ToDisplayString() == "System.ObsoleteAttribute"
                && a.ConstructorArguments.Length > 1
                && a.ConstructorArguments[1].Value is true
            );

    private static bool CanConstruct(INamedTypeSymbol type)
    {
        if (type.IsAbstract || IsObsoleteError(type))
            return false;
        var ctor = type.InstanceConstructors.FirstOrDefault(c =>
            c.Parameters.Length == 0
            && c.DeclaredAccessibility == Accessibility.Public
            && !IsObsoleteError(c)
        );
        if (ctor == null)
            return false;
        if (
            ctor.GetAttributes()
                .Any(a =>
                    a.AttributeClass?.ToDisplayString()
                    == "System.Diagnostics.CodeAnalysis.SetsRequiredMembersAttribute"
                )
        )
            return true;
        for (var current = type; current != null; current = current.BaseType)
            if (
                current
                    .GetMembers()
                    .Any(m =>
                        (m is IPropertySymbol p && p.IsRequired)
                        || (m is IFieldSymbol f && f.IsRequired)
                    )
            )
                return false;
        return true;
    }

    private static string TypeName(ITypeSymbol type) =>
        type.TypeKind == TypeKind.Dynamic
            ? "object"
            : type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
}
